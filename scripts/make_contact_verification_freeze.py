"""Generate the contact-evidence / body-envelope pre-run freeze (single file).

Work package: ``codex/bb22-contact-envelope``.  The generator follows the same
discipline as the previous freeze generators in this repository:

* ``frozen_at`` is the real UTC time (microseconds, timezone aware), the code
  commit is the actual ``git rev-parse HEAD`` and the worktree digest is the
  real ``git status --porcelain -- src scripts tests configs`` hash -- all are
  computed by this script and never accepted from the caller;
* cases/expected/vehicle/map/brake model hashes are computed here; the cases and
  expected file paths are recorded repository-relative;
* replay segments reference previous evidence by path string only
  (``previous_run_dir`` / ``previous_episode_id``); the generator checks that
  the directory exists but never reads the run contents;
* the output file is never overwritten: an existing path fails with exit code 2
  (no backdating after a run); ``--dry-run`` prints the freeze JSON and writes
  nothing;
* the write is two-pass: a placeholder worktree digest is written first, then
  the digest is recomputed with the untracked freeze file present and the file
  is rewritten, so the run entry point can re-verify
  ``worktree_state``/``code_commit`` with ``check_freeze_lineage``.

The official freeze is generated by the Lead after the code/cases/expected files
are committed and before the formal runs::

    E:\\isaac\\env_isaaclab\\Scripts\\python.exe scripts\\make_contact_verification_freeze.py

Self-test without touching the official file::

    E:\\isaac\\env_isaaclab\\Scripts\\python.exe scripts\\make_contact_verification_freeze.py \\
        --dry-run --output tmp/contact_freeze_check/contact_verification_freeze_v1.json
"""
import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'src'))

from boom_birds.evaluation.contact_plan import (  # noqa: E402
    CONTACT_CASES_SCHEMA,
    CONTACT_CONTRACT_VERSION,
    CONTACT_FREEZE_SCHEMA,
    CONTACT_EXPECTED_SCHEMA,
    DEFAULT_LOCAL_CONFIG,
    DEFAULT_MAP_CONFIG,
    DEFAULT_OUTPUT,
    DEFAULT_VEHICLE_CONFIG,
    ENVELOPE_CONTRACT_VERSION,
    REPLAY_SEGMENT_IDS,
    SEGMENT_IDS,
    SEGMENT_TABLE,
    ContactPlanError,
    build_freeze,
    build_run_plan,
    git_head,
    load_cases_file,
    load_expected_file,
    normalize_cases_payload,
    sha256_file,
    worktree_state,
)
from boom_birds.sim.map_contract import load_map_contract  # noqa: E402

DEFAULT_CASES = 'configs/scenarios/contact_verification_cases_v1.json'
DEFAULT_EXPECTED = 'configs/scenarios/contact_verification_expected_v1.json'
DEFAULT_NOTE = (
    '接触证据/包络 v2 预运行冻结（单文件 6 segment：contact_A_wall 2 + '
    'contact_B_obstacle 2 + contact_C_clearance 2 + contact_D_geometry 2 + '
    'replay_contact_inferred 2 + replay_no_contact 1 = 11 episode）。'
    '冻结后修改 src/scripts/tests/configs 必须新建版本并重跑受影响段；'
    'replay 段只引用上一轮证据路径（previous_run_dir/previous_episode_id），'
    '本冻结不重读该运行目录内容；预期非结论，实际以独立核验从原始 '
    'steps/episodes/manifest 与 contact_record 层重算为准；'
    '本冻结只覆盖当前仿真模型（PhysX 接触通道 + 球包络），不提升任何 Gate。')

_CONTACT_LIMITATIONS = [
    'PhysX contact evidence is simulation-channel evidence; it is not a real '
    'contact sensor and not hardware-in-the-loop evidence',
    'force/impulse magnitudes are policy-step window aggregates and are not '
    'event-resolved; impulse is never used as a force',
    'geometry overlap > 0.02 m is inference only and is never promoted to a '
    'PhysX contact event/force',
    'AABB/sphere envelope is a conservative bound at one measured joint state, '
    'not an all-attitude triangle-mesh sweep proof',
    'replay segments compare stored previous labels against re-simulated '
    'evidence; the referenced previous run directories are not re-read',
    'expected values are pre-run expectations, not conclusions; only independent '
    'verification promotes them',
    'this freeze covers the current simulation model only and does not raise '
    'any Gate',
]


class FreezeGenerationError(RuntimeError):
    """Generator precondition failure (missing/incoherent input files)."""


def build_parser():
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--cases', type=Path, default=Path(DEFAULT_CASES),
                        help='contact verification cases JSON (Lead)')
    parser.add_argument('--expected', type=Path,
                        default=Path(DEFAULT_EXPECTED),
                        help='contact verification expected JSON (Lead)')
    parser.add_argument('--map-config', type=Path,
                        default=Path(DEFAULT_MAP_CONFIG))
    parser.add_argument('--local-config', type=Path,
                        default=Path(DEFAULT_LOCAL_CONFIG))
    parser.add_argument('--vehicle-config', type=Path,
                        default=Path(DEFAULT_VEHICLE_CONFIG))
    parser.add_argument('--output', type=Path, default=None,
                        help='freeze output (default '
                             'configs/scenarios/contact_verification_freeze_v1.json)')
    parser.add_argument('--note', default=DEFAULT_NOTE,
                        help='freeze note (must explain pre-run expectations)')
    parser.add_argument('--dry-run', action='store_true',
                        help='print the freeze JSON, write nothing')
    return parser


def _resolve_input(path):
    path = Path(path)
    return path if path.is_absolute() else (ROOT / path)


def _repo_relative(path):
    path = Path(path)
    try:
        return path.resolve().relative_to(ROOT.resolve()).as_posix()
    except (OSError, ValueError):
        return path.as_posix()


def _require_file(path, label, hint=''):
    if not Path(path).is_file():
        message = label + ' 不存在: ' + str(path)
        if hint:
            message += '（' + hint + '）'
        raise FreezeGenerationError(message)


def _build_payload(args, worktree, frozen_at):
    cases_path = _resolve_input(args.cases)
    _require_file(cases_path, 'cases 文件',
                  'Lead 需先写入 contact_verification_cases_v1.json')
    cases_payload, cases_sha = load_cases_file(cases_path)
    if cases_payload.get('schema_version') != CONTACT_CASES_SCHEMA:
        raise FreezeGenerationError(
            'cases schema_version 必须是 %s，得到 %r'
            % (CONTACT_CASES_SCHEMA, cases_payload.get('schema_version')))
    normalized_cases = normalize_cases_payload(cases_payload, repo_root=ROOT)
    cases_file = _repo_relative(cases_path)

    expected_path = _resolve_input(args.expected)
    _require_file(expected_path, 'expected 文件',
                  'Lead 需先写入 contact_verification_expected_v1.json')
    expected_payload, expected_sha = load_expected_file(expected_path)
    if expected_payload.get('schema_version') != CONTACT_EXPECTED_SCHEMA:
        raise FreezeGenerationError(
            'expected schema_version 必须是 %s，得到 %r'
            % (CONTACT_EXPECTED_SCHEMA,
               expected_payload.get('schema_version')))
    expected_file = _repo_relative(expected_path)

    map_config_path = _resolve_input(args.map_config)
    local_config_path = _resolve_input(args.local_config)
    _require_file(map_config_path, 'map config')
    _require_file(local_config_path, 'local map config')
    contract = load_map_contract(map_config_path, local_config_path)
    map_config_file = _repo_relative(map_config_path)
    map_state = {
        'map_asset_id': contract.asset_id,
        'terrain_sha256': contract.terrain_sha256,
        'preview_sha256': contract.preview_sha256,
        'map_config_sha256': sha256_file(map_config_path),
        'map_config_file': map_config_file,
    }

    vehicle_path = _resolve_input(args.vehicle_config)
    _require_file(vehicle_path, 'vehicle config')
    vehicle_config = _repo_relative(vehicle_path)
    vehicle_config_sha256 = sha256_file(vehicle_path)
    map_config_sha256 = map_state['map_config_sha256']

    # The cases file may declare the map/vehicle configuration it was authored
    # against; the freeze must not silently use a different one.
    declared_map = cases_payload.get('map_config')
    if declared_map is not None:
        if _resolve_input(Path(str(declared_map))).resolve() \
                != map_config_path.resolve():
            raise FreezeGenerationError(
                'cases.map_config 与 --map-config 不一致: %r != %r'
                % (declared_map, map_config_file))
    declared_local = cases_payload.get('local_config')
    if declared_local is not None:
        if _resolve_input(Path(str(declared_local))).resolve() \
                != local_config_path.resolve():
            raise FreezeGenerationError(
                'cases.local_config 与 --local-config 不一致: %r'
                % (declared_local,))
    for segment in normalized_cases['segments'].values():
        for case_id, spec in segment['cases'].items():
            target = spec.get('target')
            if not isinstance(target, dict):
                continue
            for key, expected_path in (('map_config', map_config_path),
                                       ('local_config', local_config_path)):
                if _resolve_input(Path(str(target[key]))).resolve() \
                        != expected_path.resolve():
                    raise FreezeGenerationError(
                        '%s case_id=%s target.%s 与冻结 map config 不一致'
                        % (segment['segment_id'], case_id, key))
        if segment['replay_params'] is not None:
            replay_vehicle = _resolve_input(
                Path(str(segment['replay_params']['vehicle_config'])))
            if replay_vehicle.resolve() != vehicle_path.resolve():
                raise FreezeGenerationError(
                    '%s replay_params.vehicle_config 与 --vehicle-config 不一致'
                    % segment['segment_id'])

    plans = {}
    for segment_id in SEGMENT_IDS:
        segment = normalized_cases['segments'][segment_id]
        plans[segment_id] = build_run_plan(
            segment_id=segment_id,
            role=segment['role'],
            mode=segment['mode'],
            cases_file=cases_file,
            cases_sha256=cases_sha,
            case_ids=list(segment['case_ids']),
            expected_file=expected_file,
            expected_sha256=expected_sha,
            contact_contract_version=CONTACT_CONTRACT_VERSION,
            envelope_contract_version=ENVELOPE_CONTRACT_VERSION,
            vehicle_config=vehicle_config,
            vehicle_config_sha256=vehicle_config_sha256,
            map_config=map_config_file,
            map_config_sha256=map_config_sha256,
            run_params={
                'repeats': segment['repeats'],
                'cases': segment['cases'],
                **({'replay_params': segment['replay_params']}
                   if segment['replay_params'] is not None else {}),
                **({'repeat_indices': segment['repeat_indices']}
                   if any(len(indices) > 1
                          for indices in segment['repeat_indices'].values())
                   else {}),
            },
        )

    replay_sources = set()
    for segment_id in REPLAY_SEGMENT_IDS:
        for spec in normalized_cases['segments'][segment_id]['cases'].values():
            replay_sources.add(spec['previous_run_dir'])
    support_scope = {
        'scope': 'CURRENT_SIM_MODEL_ONLY',
        'evidence_domain': 'GUI Isaac Lab simulation (DirectX/D3D12); '
                           '非 SITL/HIL/实机',
        'contact_contract_version': CONTACT_CONTRACT_VERSION,
        'envelope_contract_version': ENVELOPE_CONTRACT_VERSION,
        'contact_sensor_model': 'physx_contact_sensor (filtered per-prim '
                                'force / unfiltered net force); unavailable '
                                'channel => UNKNOWN',
        'simulation_models': [
            'rigid_body_physx_contact',
            'kinematic_obstacle',
            'sphere_overlap_geometry_inference',
            'reference_frame_aabb_envelope',
        ],
        'replay_sources': sorted(replay_sources),
        'limitations': list(_CONTACT_LIMITATIONS),
    }
    freeze = build_freeze(
        frozen_at=frozen_at,
        code_commit=git_head(ROOT),
        worktree_state=worktree,
        map_state=map_state,
        cases=normalized_cases,
        segment_run_plans=plans,
        expected=expected_payload,
        expected_file=expected_file,
        expected_sha256=expected_sha,
        support_scope=support_scope,
        note=args.note,
        repo_root=ROOT,
    )
    return freeze


def _dump(payload):
    return json.dumps(payload, ensure_ascii=False, indent=2) + '\n'


def _write_exclusive(path, payload):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('x', encoding='utf-8') as handle:
        handle.write(_dump(payload))


def _print_summary(freeze, output):
    budget = freeze['budget']
    print('CONTACT_FREEZE_WRITTEN ' + str(output)
          + ' sha256=' + sha256_file(output))
    print('CODE_COMMIT ' + freeze['code_commit'])
    print('FROZEN_AT ' + freeze['frozen_at'])
    print('CASES_FILE ' + freeze['cases_file'])
    print('CASES_SHA256 ' + freeze['cases_sha256'])
    print('EXPECTED_FILE ' + freeze['expected_file'])
    print('EXPECTED_SHA256 ' + freeze['expected_sha256'])
    print('WORKTREE_STATUS_SHA256 '
          + freeze['worktree_state']['status_text_sha256'])
    print('BUDGET total_episodes=%d min_required=%d by_role=%s'
          % (budget['total_episodes'], budget['min_episodes_required'],
             json.dumps(budget['by_role'], ensure_ascii=False,
                        sort_keys=True)))
    for segment_id in SEGMENT_IDS:
        segment = freeze['segments'][segment_id]
        print('SEGMENT %s role=%s mode=%s cases=%d repeats=%d episodes=%d'
              % (segment_id, segment['role'], segment['mode'],
                 len(segment['case_ids']), segment['repeats'],
                 segment['episodes']))
        if segment['role'] == 'replay':
            for case_id in segment['case_ids']:
                spec = segment['run_plan']['run_params']['cases'][case_id]
                print('  REPLAY %s case_id=%s previous_run_dir=%s '
                      'previous_episode_id=%s previous_physical_label=%s'
                      % (segment_id, case_id, spec['previous_run_dir'],
                         spec['previous_episode_id'],
                         spec['previous_physical_label']))


def main(argv=None):
    args = build_parser().parse_args(argv)
    try:
        if args.output is not None:
            output = Path(args.output)
            if not output.is_absolute():
                output = ROOT / output
        else:
            output = ROOT / DEFAULT_OUTPUT
        if not args.dry_run and output.exists():
            print('ERROR: 冻结输出已存在（refusing to overwrite/backdate）: '
                  + str(output), file=sys.stderr)
            return 2
        frozen_at = datetime.now(timezone.utc).isoformat(timespec='microseconds')
        if args.dry_run:
            freeze = _build_payload(args, worktree_state(ROOT), frozen_at)
            print(_dump(freeze))
            return 0
        placeholder_state = worktree_state(ROOT)
        freeze = _build_payload(args, placeholder_state, frozen_at)
        _write_exclusive(output, freeze)
        actual_state = worktree_state(ROOT)
        if actual_state['status_text_sha256'] != \
                placeholder_state['status_text_sha256']:
            freeze = _build_payload(args, actual_state, frozen_at)
            Path(output).write_text(_dump(freeze), encoding='utf-8')
        _print_summary(freeze, output)
        if freeze['worktree_state']['status_text_sha256'] != \
                worktree_state(ROOT)['status_text_sha256']:
            print('WARNING: 写出后工作树状态发生变化（并发修改?）；'
                  '运行前校验可能失败，请重新生成冻结。', file=sys.stderr)
        return 0
    except (ContactPlanError, FreezeGenerationError, OSError,
            ValueError, KeyError, TypeError) as error:
        print('ERROR: ' + str(error), file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
