"""Two-class landmark data conversion, masking contract and detector metrics.

Bounded internal research only: class 0 = central_tower (green roof-light
keypoint), class 1 = similar_structure_ms1 (keypoint NOT AVAILABLE, v=0 always).

Design rules (configs/perception/landmark_two_class_label_spec_v1.json):
- YOLO pose txt is source-image normalised (same convention as the single-class
  pipeline); no letterbox transform is applied to labels.
- class0: one green roof-light keypoint; v=1 only when visible/manual reference;
  v=0 otherwise (placeholder coordinates = bbox centre, loss-masked, never a
  keypoint estimate).
- class1: keypoint v=0 ALWAYS; placeholder coordinates (bbox centre) are written
  only because the YOLO pose row format needs slots; they are masked out of the
  keypoint regression/objectness loss and must never be read as a keypoint.
- EVERY visible MS1 instance must be labelled (never background) in a frame where
  it is visible and decidable.
- single-class history stays explicit: conversion of an annotation without MS1
  confusers produces the same single-class line as the frozen single-class
  pipeline (compatibility is reported, never silently switched).

No model/ultralytics import at module import time (tests run without ML deps).
"""
import hashlib
import json
import math
from pathlib import Path

CLASS_NAMES = {0: 'central_tower', 1: 'similar_structure_ms1'}
KPT_SHAPE = (1, 3)
MS1_CONFUSER_ID = 'MAP_NATIVE_GREEN_LAMP_PILLAR_MS1'
DATA_YAML_TEMPLATE = """# Generated by scripts/landmark_train_two_class.py (gitignored output).
# Two-class landmark pose dataset: class 0 central tower, class 1 similar MS1.
path: {root}
train: images/train
val: images/val
names:
  0: central_tower
  1: similar_structure_ms1
kpt_shape: [1, 3]
"""


def sha256_file(path):
    digest = hashlib.sha256()
    with open(path, 'rb') as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b''):
            digest.update(chunk)
    return digest.hexdigest()


def load_json(path):
    with open(path, 'r', encoding='utf-8') as handle:
        return json.load(handle)


def dump_json(path, payload):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, 'w', encoding='utf-8') as handle:
        json.dump(payload, handle, indent=2, ensure_ascii=False)
        handle.write('\n')


# --- conversion --------------------------------------------------------------

def _bbox(annotation):
    geometry = annotation.get('geometry') or {}
    target = annotation.get('target') or {}
    if target.get('present') is not True:
        return None
    bbox = geometry.get('bbox_xywh')
    if bbox is None:
        return None
    return [float(value) for value in bbox]


def _annotation_size(annotation):
    width = float(annotation.get('image_width') or 0)
    height = float(annotation.get('image_height') or 0)
    if width <= 0 or height <= 0:
        raise ValueError('annotation %r has invalid image size' % annotation.get('frame_id'))
    return width, height


def _keypoint_visible(annotation):
    geometry = annotation.get('geometry') or {}
    keypoint = geometry.get('keypoint')
    return (keypoint is not None
            and keypoint.get('visible') is True
            and geometry.get('reference_status') == 'MANUAL_APPROX')


def _class1_instances(annotation):
    instances = []
    for confuser in annotation.get('confusers') or []:
        if not isinstance(confuser, dict):
            continue
        is_ms1 = (confuser.get('confuser_id') == MS1_CONFUSER_ID
                  or str(confuser.get('description', '')).startswith('map-native slender green-lamp pillar'))
        if not is_ms1 or confuser.get('verified') is not True:
            continue
        bbox = confuser.get('bbox_xywh')
        if bbox is None:
            continue
        instances.append({
            'class_id': 1,
            'bbox_xywh': [float(value) for value in bbox],
            'keypoint_visible': False,
            'confuser_id': confuser.get('confuser_id'),
            'verification_source': confuser.get('verification_source'),
        })
    return instances


def annotation_to_two_class_instances(annotation):
    """Return the instance list for one v2.1 annotation, both classes, source px."""
    width, height = _annotation_size(annotation)
    instances = []
    bbox = _bbox(annotation)
    gt_unobservable = False
    target = annotation.get('target') or {}
    if (target.get('undecidable') is True
            or (target.get('present') is True and bbox is None)):
        gt_unobservable = True
    if bbox is not None:
        instances.append({
            'class_id': 0,
            'bbox_xywh': bbox,
            'keypoint_visible': _keypoint_visible(annotation),
            'keypoint': ((annotation.get('geometry') or {}).get('keypoint')
                         if _keypoint_visible(annotation) else None),
            'reference_status': (annotation.get('geometry') or {}).get('reference_status'),
        })
    for instance in _class1_instances(annotation):
        instances.append(instance)
    sidecar = {
        'frame_id': annotation.get('frame_id'),
        'image': annotation.get('image'),
        'image_sha256': annotation.get('image_sha256'),
        'image_width': width,
        'image_height': height,
        'split': (annotation.get('source') or {}).get('split'),
        'family': (annotation.get('source') or {}).get('family'),
        'group_id': (annotation.get('source') or {}).get('group_id'),
        'dataset_role': annotation.get('dataset_role'),
        'tower_present': target.get('present') is True,
        'ms1_present': any(instance['class_id'] == 1 for instance in instances),
        'gt_unobservable': gt_unobservable,
        'identity_ambiguity': target.get('ambiguous') is True,
        'negative_type': annotation.get('negative_type'),
        'instances': [{'class_id': instance['class_id'],
                       'class_name': CLASS_NAMES[instance['class_id']],
                       'bbox_xywh': instance['bbox_xywh'],
                       'keypoint_visible': instance['keypoint_visible']}
                      for instance in instances],
    }
    return instances, sidecar


def format_two_class_label_line(instance, width, height):
    """8-field YOLO pose line: class cx cy w h kx ky v (source-image normalised)."""
    x, y, w, h = instance['bbox_xywh']
    cx = (x + w / 2.0) / width
    cy = (y + h / 2.0) / height
    bw = w / width
    bh = h / height
    if instance['class_id'] == 0 and instance.get('keypoint_visible'):
        if instance.get('keypoint') is not None:
            keypoint = instance['keypoint']
            kx = float(keypoint['x']) / width
            ky = float(keypoint['y']) / height
        else:
            kx = float(instance['keypoint_px'][0]) / width
            ky = float(instance['keypoint_px'][1]) / height
        visibility = 1
    elif instance['class_id'] == 1:
        # class1: the frozen two-class spec requires 0,0,v=0; the bbox centre is
        # FORBIDDEN as a keypoint (the slot is masked out of every keypoint loss).
        kx, ky = 0.0, 0.0
        visibility = 0
    else:
        # class0 with unavailable reference: historical single-class placeholder
        # (bbox centre, v=0), masked out of every keypoint loss / denominator.
        kx, ky = cx, cy
        visibility = 0
    # visibility is rendered like the frozen single-class formatter ("%.6f") so
    # a class0-only frame stays byte-identical to the historical single-class
    # label; YOLO parses the value as float anyway.
    return ' '.join([str(int(instance['class_id'])),
                     '%.6f' % round(cx, 6), '%.6f' % round(cy, 6),
                     '%.6f' % round(bw, 6), '%.6f' % round(bh, 6),
                     '%.6f' % round(kx, 6), '%.6f' % round(ky, 6),
                     '%.6f' % float(visibility)])


def keypoint_mask_for_instances(instances):
    """Keypoint-loss mask contract: 1 only for class0 with a usable reference."""
    return [1 if (instance['class_id'] == 0 and instance.get('keypoint_visible')) else 0
            for instance in instances]


def convert_annotation(annotation, split=None):
    """Convert one annotation to two-class label lines plus a sidecar."""
    source = annotation.get('source') or {}
    if split is not None and source.get('split') != split:
        return None
    width, height = _annotation_size(annotation)
    instances, sidecar = annotation_to_two_class_instances(annotation)
    lines = [format_two_class_label_line(instance, width, height) for instance in instances]
    sidecar['label_lines'] = lines
    sidecar['class0_lines'] = sum(1 for instance in instances if instance['class_id'] == 0)
    sidecar['class1_lines'] = sum(1 for instance in instances if instance['class_id'] == 1)
    if not instances:
        if sidecar['gt_unobservable']:
            sidecar['exclusion_reason'] = 'GT_UNOBSERVABLE'
        elif not sidecar['tower_present']:
            sidecar['exclusion_reason'] = 'BACKGROUND_NO_INSTANCE'
        else:
            sidecar['exclusion_reason'] = 'NO_INSTANCE'
    return {'frame_id': annotation['frame_id'], 'lines': lines, 'sidecar': sidecar}


def convert_document(document, split=None):
    records = []
    excluded = []
    for annotation in document.get('annotations', []):
        record = convert_annotation(annotation, split=split)
        if record is None:
            continue
        if record['lines']:
            records.append(record)
        else:
            excluded.append({'frame_id': record['frame_id'],
                             'reason': record['sidecar'].get('exclusion_reason')})
    counts = {'frames_in_document': len(document.get('annotations', [])),
              'frames_with_labels': len(records),
              'class0_instances': sum(record['sidecar']['class0_lines'] for record in records),
              'class1_instances': sum(record['sidecar']['class1_lines'] for record in records),
              'same_frame_instances': sum(1 for record in records
                                          if record['sidecar']['class0_lines'] and record['sidecar']['class1_lines']),
              'excluded_frames': len(excluded),
              'class1_keypoint_visibility_histogram': _visibility_histogram(records)}
    return {'records': records, 'excluded': excluded, 'counts': counts}


def _visibility_histogram(records):
    histogram = {0: {0: 0, 1: 0}, 1: {0: 0, 1: 0}}
    for record in records:
        for line in record['lines']:
            parts = line.split()
            class_id = int(parts[0])
            visibility = int(float(parts[7]))
            histogram[class_id][visibility] = histogram[class_id].get(visibility, 0) + 1
    return {'class%d' % key: {'v0': value.get(0, 0), 'v1': value.get(1, 0)}
            for key, value in histogram.items()}


def validate_document(document, image_root):
    """Fail-loud QA for two-class annotations (schema + per-frame instance rules)."""
    problems = []
    for index, annotation in enumerate(document.get('annotations', [])):
        prefix = 'annotations[%d]' % index
        frame = annotation.get('frame_id')
        if not frame:
            problems.append(prefix + ': missing frame_id')
            continue
        image = Path(image_root) / str(annotation.get('image') or '')
        if not image.is_file():
            problems.append(prefix + ': image missing: %s' % annotation.get('image'))
        width, height = _annotation_size(annotation)
        instances, sidecar = annotation_to_two_class_instances(annotation)
        for instance in instances:
            x, y, w, h = instance['bbox_xywh']
            if w <= 0 or h <= 0 or x < 0 or y < 0 or x + w > width + 1e-6 or y + h > height + 1e-6:
                problems.append(prefix + ': class%d bbox out of bounds' % instance['class_id'])
        if (annotation.get('target') or {}).get('present') is True and (annotation.get('geometry') or {}).get('bbox_xywh') is None:
            if not (annotation.get('target') or {}).get('occluded'):
                problems.append(prefix + ': present target without bbox must be occluded/GT_UNOBSERVABLE')
        if not instances and sidecar['tower_present'] and not sidecar['gt_unobservable']:
            problems.append(prefix + ': present, decidable target frame has no label instance')
        if not instances and not sidecar['tower_present'] and not sidecar['ms1_present']:
            pass  # explicit background frame: empty label file is valid
    return {'ok': not problems, 'problems': problems,
            'annotations': len(document.get('annotations', []))}


# --- dataset build -----------------------------------------------------------

def build_dataset(annotation_docs, out_dir, repo_root, splits=('train', 'val'),
                  model_yaml=None):
    """Write images/labels/data.yaml from annotation documents (repo-relative images)."""
    repo_root = Path(repo_root).resolve()
    out_dir = Path(out_dir)
    summary = {'schema_version': 'dsh.landmark_two_class_dataset.v1',
               'splits': {}, 'classes': CLASS_NAMES, 'kpt_shape': list(KPT_SHAPE)}
    if isinstance(annotation_docs, dict):
        documents_by_split = {key: list(value) for key, value in annotation_docs.items()}
    else:
        documents_by_split = {split: annotation_docs for split in splits}
    for split in splits:
        labels_dir = out_dir / 'labels' / split
        images_dir = out_dir / 'images' / split
        labels_dir.mkdir(parents=True, exist_ok=True)
        images_dir.mkdir(parents=True, exist_ok=True)
        counts = {'class0': 0, 'class1': 0, 'frames': 0, 'excluded': 0, 'same_frame': 0}
        sidecars = []
        image_by_frame = {}
        for document in documents_by_split.get(split, []):
            if document.get('schema_version') == TWO_CLASS_SCHEMA:
                for frame in document.get('frames') or []:
                    image_by_frame[frame.get('frame_id')] = frame.get('image')
            else:
                for annotation in document.get('annotations') or []:
                    image_by_frame[annotation.get('frame_id')] = annotation.get('image')
        for document in documents_by_split.get(split, []):
            if document.get('schema_version') == TWO_CLASS_SCHEMA:
                qa = validate_two_class_file(document, repo_root)
                if not qa['ok']:
                    raise ValueError('two-class annotation QA failed: %s' % qa['problems'][:5])
                converted = convert_two_class_document(document, split=split)
            else:
                converted = convert_document(document, split=split)
            for excluded in converted['excluded']:
                if excluded.get('reason') != 'BACKGROUND_NO_INSTANCE':
                    counts['excluded'] += 1
                    continue
                # empty-label background negatives must stay in the dataset
                frame = excluded['frame_id']
                source = repo_root / str(image_by_frame.get(frame) or '')
                if source.is_file():
                    target_image = images_dir / frame
                    if not target_image.is_file():
                        import shutil
                        shutil.copyfile(source, target_image)
                    (labels_dir / (Path(frame).stem + '.txt')).write_text('', encoding='utf-8')
                    counts['frames'] += 1
            for record in converted['records']:
                frame = record['frame_id']
                source = repo_root / str(record['sidecar']['image'])
                if not source.is_file():
                    raise FileNotFoundError('image not found: %s' % source)
                target_image = images_dir / frame
                if not target_image.is_file():
                    import shutil
                    shutil.copyfile(source, target_image)
                (labels_dir / (Path(frame).stem + '.txt')).write_text(
                    '\n'.join(record['lines']) + '\n', encoding='utf-8')
                counts['class0'] += record['sidecar']['class0_lines']
                counts['class1'] += record['sidecar']['class1_lines']
                counts['frames'] += 1
                if record['sidecar']['class0_lines'] and record['sidecar']['class1_lines']:
                    counts['same_frame'] += 1
                sidecars.append(record['sidecar'])
        sidecar_path = out_dir / 'sidecars' / ('%s_sidecar.jsonl' % split)
        sidecar_path.parent.mkdir(parents=True, exist_ok=True)
        with open(sidecar_path, 'w', encoding='utf-8') as handle:
            for sidecar in sidecars:
                handle.write(json.dumps(sidecar, ensure_ascii=False) + '\n')
        summary['splits'][split] = {'counts': counts,
                                    'label_files': counts['frames'],
                                    'sidecar': str(sidecar_path),
                                    'sidecar_sha256': sha256_file(sidecar_path)}
    data_yaml = out_dir / 'data.yaml'
    data_yaml.write_text(DATA_YAML_TEMPLATE.format(
        root=str(out_dir.resolve()).replace('\\', '/')), encoding='utf-8')
    summary['data_yaml'] = {'path': str(data_yaml), 'sha256': sha256_file(data_yaml)}
    if model_yaml:
        summary['model_yaml'] = {'path': str(model_yaml),
                                 'sha256': sha256_file(model_yaml)}
    dump_json(out_dir / 'dataset_build.json', summary)
    return summary


# --- detector metrics --------------------------------------------------------

def load_predictions(path):
    rows = []
    with open(path, 'r', encoding='utf-8') as handle:
        for line in handle:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    return rows


def _iou(a, b):
    ax1, ay1, ax2, ay2 = a
    bx1, by1, bx2, by2 = b
    inter = max(0.0, min(ax2, bx2) - max(ax1, bx1)) * max(0.0, min(ay2, by2) - max(ay1, by1))
    area_a = max(0.0, ax2 - ax1) * max(0.0, ay2 - ay1)
    area_b = max(0.0, bx2 - bx1) * max(0.0, by2 - by1)
    return inter / max(area_a + area_b - inter, 1e-9)


def _xywh_to_xyxy(bbox):
    x, y, w, h = bbox
    return [x, y, x + w, y + h]


def evaluate_two_class(predictions, annotations, *, tau_det=0.25, tau_iou=0.3,
                       tau_px=3.0, fx=160.0, cx=160.0):
    """Detector-level metrics with explicit numerators/denominators.

    Consumer (identity+bearing) success metrics are NOT defined here; they are
    owned by evaltool's consumer protocol.  This function covers the pilot-gate
    detector/identity-disambiguation numbers from the two-class protocol.
    """
    annotation_by_frame = {annotation['frame_id']: annotation for annotation in annotations}
    prediction_by_frame = {row.get('frame_id'): row for row in predictions}
    counters = {
        'tower_tp': 0, 'tower_fn': 0, 'tower_claim_tp': 0, 'tower_claim_fp': 0,
        'ms1_tp': 0, 'ms1_fn': 0, 'ms1_claim_tp': 0, 'ms1_claim_fp': 0,
        'ms1_only_frames': 0, 'ms1_only_wrong_tower_claims': 0,
        'same_frame_frames': 0, 'same_frame_correct': 0,
        'reference_available_frames': 0, 'reference_emitted': 0, 'reference_correct': 0,
        'reference_unavailable_frames': 0, 'false_reference': 0,
        'bearing_errors_deg': [], 'pixel_errors_px': [],
        'gt_unobservable_frames': 0, 'tower_claims_on_gt_unobservable': 0,
    }
    for frame, annotation in annotation_by_frame.items():
        row = prediction_by_frame.get(frame) or {}
        detections = [detection for detection in (row.get('detections') or [])
                      if float(detection.get('score') or 0) >= tau_det]
        class0 = [detection for detection in detections if int(detection.get('class_id', 0)) == 0]
        class1 = [detection for detection in detections if int(detection.get('class_id', -1)) == 1]
        instances, sidecar = annotation_to_two_class_instances(annotation)
        tower_gt = next((instance for instance in instances if instance['class_id'] == 0), None)
        ms1_gts = [instance for instance in instances if instance['class_id'] == 1]
        if sidecar['gt_unobservable']:
            counters['gt_unobservable_frames'] += 1
            if class0:
                counters['tower_claims_on_gt_unobservable'] += 1
        if tower_gt is not None:
            counters['tower_fn'] += 1
            gt_box = _xywh_to_xyxy(tower_gt['bbox_xywh'])
            best = max(class0, key=lambda det: _iou(_xywh_to_xyxy(det['bbox_xywh']), gt_box),
                       default=None)
            if best is not None and _iou(_xywh_to_xyxy(best['bbox_xywh']), gt_box) >= tau_iou:
                counters['tower_tp'] += 1
                counters['tower_fn'] -= 1
            # claim precision: every class0 detection either matches tower or is FP
            for detection in class0:
                if _iou(_xywh_to_xyxy(detection['bbox_xywh']), gt_box) >= tau_iou:
                    counters['tower_claim_tp'] += 1
                else:
                    counters['tower_claim_fp'] += 1
            geometry = annotation.get('geometry') or {}
            keypoint_visible = (geometry.get('keypoint') is not None
                                and geometry.get('reference_status') == 'MANUAL_APPROX')
            if keypoint_visible:
                counters['reference_available_frames'] += 1
                if best is not None and best.get('keypoint_px'):
                    counters['reference_emitted'] += 1
                    error = math.hypot(float(best['keypoint_px'][0]) - float(geometry['keypoint']['x']),
                                       float(best['keypoint_px'][1]) - float(geometry['keypoint']['y']))
                    counters['pixel_errors_px'].append(error)
                    if error <= tau_px:
                        counters['reference_correct'] += 1
                    counters['bearing_errors_deg'].append(abs(
                        math.degrees(math.atan2(float(best['keypoint_px'][0]) - cx, fx))
                        - math.degrees(math.atan2(float(geometry['keypoint']['x']) - cx, fx))))
            else:
                counters['reference_unavailable_frames'] += 1
                if best is not None and best.get('keypoint_px'):
                    counters['false_reference'] += 1
        else:
            # no class0 GT: any class0 claim is a false claim
            counters['tower_claim_fp'] += len(class0)
        if ms1_gts:
            counters['ms1_fn'] += len(ms1_gts)
            used = set()
            for detection in class1:
                det_box = _xywh_to_xyxy(detection['bbox_xywh'])
                match = None
                for index, gt in enumerate(ms1_gts):
                    if index in used:
                        continue
                    if _iou(det_box, _xywh_to_xyxy(gt['bbox_xywh'])) >= tau_iou:
                        match = index
                        break
                if match is not None:
                    used.add(match)
                    counters['ms1_tp'] += 1
                    counters['ms1_fn'] -= 1
                    counters['ms1_claim_tp'] += 1
                else:
                    counters['ms1_claim_fp'] += 1
            if tower_gt is None:
                counters['ms1_only_frames'] += 1
                if class0:
                    counters['ms1_only_wrong_tower_claims'] += 1
            if tower_gt is not None:
                counters['same_frame_frames'] += 1
                tower_ok = any(_iou(_xywh_to_xyxy(detection['bbox_xywh']),
                                    _xywh_to_xyxy(tower_gt['bbox_xywh'])) >= tau_iou
                               for detection in class0)
                ms1_ok = len(used) == len(ms1_gts) or all(
                    any(_iou(_xywh_to_xyxy(detection['bbox_xywh']),
                             _xywh_to_xyxy(gt['bbox_xywh'])) >= tau_iou for detection in class1)
                    for gt in ms1_gts)
                if tower_ok and ms1_ok:
                    counters['same_frame_correct'] += 1

    def ratio(num, den):
        return (num / den) if den else None

    return {
        'thresholds': {'tau_det': tau_det, 'tau_iou': tau_iou, 'tau_px': tau_px},
        'tower': {'gt_positives': counters['tower_tp'] + counters['tower_fn'],
                  'tp': counters['tower_tp'], 'fn': counters['tower_fn'],
                  'recall': ratio(counters['tower_tp'], counters['tower_tp'] + counters['tower_fn']),
                  'claim_tp': counters['tower_claim_tp'],
                  'claim_fp': counters['tower_claim_fp'],
                  'precision': ratio(counters['tower_claim_tp'],
                                     counters['tower_claim_tp'] + counters['tower_claim_fp'])},
        'ms1': {'gt_instances': counters['ms1_tp'] + counters['ms1_fn'],
                'tp': counters['ms1_tp'], 'fn': counters['ms1_fn'],
                'recall': ratio(counters['ms1_tp'], counters['ms1_tp'] + counters['ms1_fn']),
                'claim_tp': counters['ms1_claim_tp'], 'claim_fp': counters['ms1_claim_fp'],
                'precision': ratio(counters['ms1_claim_tp'],
                                   counters['ms1_claim_tp'] + counters['ms1_claim_fp'])},
        'ms1_only': {'frames': counters['ms1_only_frames'],
                     'wrong_tower_claims': counters['ms1_only_wrong_tower_claims']},
        'same_frame': {'frames': counters['same_frame_frames'],
                       'correct': counters['same_frame_correct'],
                       'rate': ratio(counters['same_frame_correct'], counters['same_frame_frames'])},
        'identity': {'class0_claims': counters['tower_claim_tp'] + counters['tower_claim_fp'],
                     'precision': ratio(counters['tower_claim_tp'],
                                        counters['tower_claim_tp'] + counters['tower_claim_fp'])},
        'reference': {'available_frames': counters['reference_available_frames'],
                      'emitted': counters['reference_emitted'],
                      'correct_within_tau_px': counters['reference_correct'],
                      'coverage': ratio(counters['reference_correct'],
                                        counters['reference_available_frames']),
                      'unavailable_frames': counters['reference_unavailable_frames'],
                      'false_reference': counters['false_reference'],
                      'false_reference_rate': ratio(counters['false_reference'],
                                                    counters['reference_unavailable_frames']),
                      'pixel_error_px': _stats(counters['pixel_errors_px']),
                      'bearing_error_deg': _stats(counters['bearing_errors_deg'])},
        'gt_unobservable': {'frames': counters['gt_unobservable_frames'],
                            'tower_claims': counters['tower_claims_on_gt_unobservable']},
        'consumer_metrics': {'status': 'PENDING_EVALTOOL_T34',
                             'note': 'consumer confirmed-identity success is owned by evaltool; not defined here'},
    }


def _stats(values):
    if not values:
        return {'count': 0}
    values = sorted(values)
    def percentile(q):
        index = min(len(values) - 1, max(0, int(round((q / 100.0) * (len(values) - 1)))))
        return values[index]
    return {'count': len(values), 'median': percentile(50),
            'p90': percentile(90), 'max': values[-1]}


def predictions_from_ultralytics(result, frame_id):
    """Map one ultralytics pose result to the prediction row used above (no GT)."""
    detections = []
    boxes = getattr(result, 'boxes', None)
    keypoints = getattr(result, 'keypoints', None)
    if boxes is not None and len(boxes):
        xyxy = boxes.xyxy.cpu().numpy()
        conf = boxes.conf.cpu().numpy()
        classes = boxes.cls.cpu().numpy()
        kpts = None
        if keypoints is not None and getattr(keypoints, 'xy', None) is not None and len(keypoints):
            kpts = keypoints.xy.cpu().numpy()
        for index in range(len(xyxy)):
            x1, y1, x2, y2 = [float(value) for value in xyxy[index]]
            detection = {'class_id': int(classes[index]), 'score': float(conf[index]),
                         'bbox_xywh': [x1, y1, x2 - x1, y2 - y1]}
            if kpts is not None and index < len(kpts) and len(kpts[index]):
                detection['keypoint_px'] = [float(kpts[index][0][0]), float(kpts[index][0][1])]
                conf_tensor = getattr(keypoints, 'conf', None)
                if conf_tensor is not None and len(conf_tensor):
                    try:
                        value = conf_tensor[index]
                        flat = value.reshape(-1) if hasattr(value, 'reshape') else value
                        detection['keypoint_confidence'] = float(flat[0])
                    except (IndexError, TypeError, ValueError, AttributeError):
                        pass
            detections.append(detection)
    return {'frame_id': frame_id, 'detections': detections}

# --- new two-class annotation schema (T31/T32 frozen format) -----------------
TWO_CLASS_SCHEMA = 'dsh.landmark_two_class_annotations.v1'
COORDINATE_SPACE = {'bbox': 'SOURCE_IMAGE_PIXELS_XYXY',
                    'keypoint': 'SOURCE_IMAGE_PIXELS_NORMALIZED_01'}
IDENTITY_AMBIGUITY = ('NONE', 'UNCERTAIN', 'AMBIGUOUS')
GT_UNCERTAINTY = ('NONE', 'FULLY_OCCLUDED', 'REFERENCE_UNRESOLVED', 'INSTANCE_UNRESOLVED')
OCCLUSION_VALUES = ('NONE', 'PARTIAL', 'FULL')


def _frame_instances(frame):
    """Validate/normalise instances of one new-schema frame (source px boxes, 0-1 kpt)."""
    problems = []
    instances = []
    width = float(frame.get('image_width') or 0)
    height = float(frame.get('image_height') or 0)
    if width <= 0 or height <= 0:
        return [], ['invalid image size']
    for index, instance in enumerate(frame.get('instances') or []):
        prefix = 'instances[%d]' % index
        class_id = instance.get('class')
        if class_id not in (0, 1):
            problems.append(prefix + ': class must be 0 or 1')
            continue
        bbox = instance.get('bbox_xyxy')
        if not (isinstance(bbox, list) and len(bbox) == 4):
            problems.append(prefix + ': bbox_xyxy must be [x1,y1,x2,y2]')
            continue
        x1, y1, x2, y2 = [float(value) for value in bbox]
        if not (0 <= x1 < x2 <= width and 0 <= y1 < y2 <= height):
            problems.append(prefix + ': bbox out of bounds or empty')
            continue
        if x2 <= 1.0 and y2 <= 1.0 and width > 2:
            problems.append(prefix + ': bbox looks normalised; labels must be source pixels')
            continue
        v = instance.get('v')
        if v not in (0, 1):
            problems.append(prefix + ': v must be 0 or 1')
            continue
        kx = instance.get('keypoint_x')
        ky = instance.get('keypoint_y')
        reference_available = instance.get('reference_available')
        if class_id == 1:
            if v != 0 or kx is not None or ky is not None or reference_available is not False:
                problems.append(prefix + ': class1 keypoint must be null/v=0/reference_available=false')
                continue
        else:
            if v == 1:
                if kx is None or ky is None:
                    problems.append(prefix + ': class0 v=1 requires keypoint_x/keypoint_y')
                    continue
                if not (0.0 <= float(kx) <= 1.0 and 0.0 <= float(ky) <= 1.0):
                    problems.append(prefix + ': class0 keypoint must be normalised [0,1]')
                    continue
                if reference_available is not True:
                    problems.append(prefix + ': class0 v=1 requires reference_available=true')
                    continue
            else:
                if kx is not None or ky is not None:
                    problems.append(prefix + ': class0 v=0 requires null keypoint')
                    continue
                if reference_available is not False:
                    problems.append(prefix + ': class0 v=0 requires reference_available=false')
                    continue
        instances.append({'class_id': class_id,
                          'bbox_xywh': [x1, y1, x2 - x1, y2 - y1],
                          'keypoint_visible': class_id == 0 and v == 1,
                          'keypoint_px': ([float(kx) * width, float(ky) * height]
                                          if class_id == 0 and v == 1 else None),
                          'v': v,
                          'reference_available': reference_available,
                          'verified_source': instance.get('verified_source')})
    return instances, problems


def validate_two_class_file(document, repo_root):
    """Fail-loud QA for dsh.landmark_two_class_annotations.v1 files."""
    problems = []
    if document.get('schema_version') != TWO_CLASS_SCHEMA:
        return {'ok': False, 'problems': ['unsupported schema_version: %r'
                                          % document.get('schema_version')],
                'frames': 0}
    space = document.get('coordinate_space') or {}
    if space.get('bbox') != COORDINATE_SPACE['bbox']:
        problems.append('coordinate_space.bbox must be %s' % COORDINATE_SPACE['bbox'])
    if space.get('keypoint') != COORDINATE_SPACE['keypoint']:
        problems.append('coordinate_space.keypoint must be %s' % COORDINATE_SPACE['keypoint'])
    seen = set()
    frames = document.get('frames') or []
    for index, frame in enumerate(frames):
        prefix = 'frames[%d]' % index
        frame_id = frame.get('frame_id')
        if not frame_id:
            problems.append(prefix + ': missing frame_id')
            continue
        if frame_id in seen:
            problems.append(prefix + ': duplicate frame_id %r' % frame_id)
        seen.add(frame_id)
        image = Path(repo_root) / str(frame.get('image') or '')
        if not image.is_file():
            problems.append(prefix + ': image missing: %s' % frame.get('image'))
        else:
            if frame.get('image_sha256') and sha256_file(image) != frame.get('image_sha256'):
                problems.append(prefix + ': image sha mismatch')
        if frame.get('identity_ambiguity') not in IDENTITY_AMBIGUITY:
            problems.append(prefix + ': identity_ambiguity must be one of %s' % (IDENTITY_AMBIGUITY,))
        if frame.get('gt_uncertainty') not in GT_UNCERTAINTY:
            problems.append(prefix + ': gt_uncertainty must be one of %s' % (GT_UNCERTAINTY,))
        if frame.get('occlusion') not in OCCLUSION_VALUES:
            problems.append(prefix + ': occlusion must be one of %s' % (OCCLUSION_VALUES,))
        instances, instance_problems = _frame_instances(frame)
        problems.extend(prefix + ': ' + problem for problem in instance_problems)
        class0 = [instance for instance in instances if instance['class_id'] == 0]
        class1 = [instance for instance in instances if instance['class_id'] == 1]
        if len(class0) > 1:
            problems.append(prefix + ': more than one class0 instance')
        if bool(frame.get('tower_present')) != bool(class0):
            fully_occluded = (frame.get('tower_present') is True
                              and frame.get('gt_uncertainty') == 'FULLY_OCCLUDED')
            if not fully_occluded:
                problems.append(prefix + ': tower_present and class0 instances disagree')
        if bool(frame.get('ms1_present')) != bool(class1):
            problems.append(prefix + ': ms1_present and class1 instances disagree')
        if frame.get('tower_present') is False and frame.get('ms1_present') is False and instances:
            problems.append(prefix + ': negative frame must have no instances')
    return {'ok': not problems, 'problems': problems, 'frames': len(frames)}


def convert_two_class_frame(frame):
    """Convert one new-schema frame to YOLO lines (source-image normalised)."""
    width = float(frame['image_width'])
    height = float(frame['image_height'])
    instances, problems = _frame_instances(frame)
    if problems:
        raise ValueError('invalid frame %r: %s' % (frame.get('frame_id'), problems[:3]))
    lines = [format_two_class_label_line(instance, width, height) for instance in instances]
    sidecar = {'frame_id': frame.get('frame_id'),
               'image': frame.get('image'),
               'image_sha256': frame.get('image_sha256'),
               'split': frame.get('split'),
               'family': frame.get('family'),
               'group_id': frame.get('group_id'),
               'tower_present': frame.get('tower_present'),
               'ms1_present': frame.get('ms1_present'),
               'identity_ambiguity': frame.get('identity_ambiguity'),
               'gt_uncertainty': frame.get('gt_uncertainty'),
               'occlusion': frame.get('occlusion'),
               'gt_unobservable': (frame.get('tower_present') is True
                                   and frame.get('gt_uncertainty') == 'FULLY_OCCLUDED'),
               'class0_lines': sum(1 for instance in instances if instance['class_id'] == 0),
               'class1_lines': sum(1 for instance in instances if instance['class_id'] == 1),
               'label_lines': lines}
    return {'frame_id': frame.get('frame_id'), 'lines': lines, 'sidecar': sidecar}


def convert_two_class_document(document, split=None):
    """Convert a new-schema shard document to records (split filter optional)."""
    records = []
    excluded = []
    for frame in document.get('frames') or []:
        frame_split = frame.get('split')
        if split is not None and frame_split is not None and frame_split != split:
            continue
        record = convert_two_class_frame(frame)
        if record['lines']:
            records.append(record)
        else:
            excluded.append({'frame_id': record['frame_id'],
                             'reason': 'GT_UNOBSERVABLE' if record['sidecar']['gt_unobservable']
                             else 'BACKGROUND_NO_INSTANCE'})
    class1_histogram = {'v0': 0, 'v1': 0}
    class0_histogram = {'v0': 0, 'v1': 0}
    for record in records:
        for line in record['lines']:
            parts = line.split()
            visibility = int(float(parts[7]))
            if int(parts[0]) == 1:
                class1_histogram['v%d' % visibility] += 1
            else:
                class0_histogram['v%d' % visibility] += 1
    counts = {'frames_in_document': len(document.get('frames') or []),
              'frames_with_labels': len(records),
              'class0_instances': class0_histogram['v0'] + class0_histogram['v1'],
              'class1_instances': class1_histogram['v0'] + class1_histogram['v1'],
              'class0_v': class0_histogram, 'class1_v': class1_histogram,
              'same_frame_instances': sum(1 for record in records
                                          if record['sidecar']['class0_lines']
                                          and record['sidecar']['class1_lines']),
              'excluded_frames': len(excluded)}
    return {'records': records, 'excluded': excluded, 'counts': counts}


def merge_two_class_shards(shard_paths, out_path, repo_root):
    """Merge A/B shard documents (and a val_main MS1 document) into one file.

    Shards keep their own bytes; the merged file only frames them with explicit
    provenance, a duplicate-frame check and the QA summary.  Coordinate space must
    be identical in every shard.
    """
    merged = {'schema_version': TWO_CLASS_SCHEMA,
              'status': 'MERGED_TWO_CLASS_TRAIN_SHARDS',
              'coordinate_space': dict(COORDINATE_SPACE),
              'sources': [],
              'frames': []}
    seen = set()
    problems = []
    for shard_path in shard_paths:
        shard_path = Path(shard_path)
        document = load_json(shard_path)
        if document.get('schema_version') != TWO_CLASS_SCHEMA:
            problems.append('shard %s has unsupported schema %r'
                            % (shard_path, document.get('schema_version')))
            continue
        if (document.get('coordinate_space') or {}) != COORDINATE_SPACE:
            problems.append('shard %s coordinate_space differs: %r'
                            % (shard_path, document.get('coordinate_space')))
            continue
        qa = validate_two_class_file(document, repo_root)
        if not qa['ok']:
            problems.extend('shard %s QA: %s' % (shard_path.name, item)
                            for item in qa['problems'][:10])
        merged['sources'].append({'path': str(shard_path),
                                  'sha256': sha256_file(shard_path),
                                  'frames': len(document.get('frames') or []),
                                  'qa_ok': qa['ok']})
        for frame in document.get('frames') or []:
            frame_id = frame.get('frame_id')
            if frame_id in seen:
                problems.append('duplicate frame across shards: %r' % frame_id)
                continue
            seen.add(frame_id)
            merged['frames'].append(frame)
    if problems:
        return {'ok': False, 'problems': problems}
    merged_path = Path(out_path)
    dump_json(merged_path, merged)
    return {'ok': True, 'problems': [], 'path': str(merged_path),
            'sha256': sha256_file(merged_path),
            'frames': len(merged['frames']),
            'sources': merged['sources']}

# --- checkpoint selection rules (frozen before each pilot) -------------------

SELECTION_RULES = ('r1_detector', 'r2_joint')


def selection_metrics(candidate):
    """Detector/identity metrics used by the frozen checkpoint-selection rule."""
    tower = (((candidate.get('tower_metrics_val_main') or {}).get('tower')) or {}).get('recall')
    ms1 = (((candidate.get('identity_metrics') or {}).get('ms1')) or {}).get('recall')
    same = (((candidate.get('identity_metrics') or {}).get('same_frame')) or {}).get('rate')
    return {'tower_recall_val_main': tower, 'ms1_recall_identity': ms1,
            'same_frame_rate_identity': same}


def candidate_rank_key(candidate, rule):
    """Sort key (ascending) for a frozen rule; higher scores first, name as last tie-break.

    r1_detector (R1): tower recall -> MS1 recall -> same-frame -> candidate name.
    r2_joint (R2, frozen before training): tower recall + MS1 recall (equal weight)
        -> same-frame selection rate -> candidate name.
    """
    metrics = selection_metrics(candidate)
    tower = metrics['tower_recall_val_main'] or 0.0
    ms1 = metrics['ms1_recall_identity'] or 0.0
    same = metrics['same_frame_rate_identity'] or 0.0
    name = str(candidate.get('candidate', ''))
    if rule == 'r2_joint':
        return (-(tower + ms1), -same, name)
    return (-tower, -ms1, -same, name)
